// The context RENDERER: model in, markdown out.
//
// Pure — no fs, no vite, no vue-component-meta, no clock. Everything it needs is on the model `model.mjs` builds, which is what makes it the half of this pipeline that can be tested by calling it. See context.spec.mjs.

/** Where a component's own file sits, relative to the index beside it. */
export function componentPath(name) {
  return `components/${name}.md`
}

/** Markdown table cells can't hold a raw `|`, and prop types are full of them. */
function cell(text) {
  return String(text ?? '').replace(/\|/g, '\\|').replace(/\n+/g, ' ').trim()
}

const BANNER = [
  '<!-- AUTO-GENERATED by scripts/generate-context.mjs — do not edit by hand. -->',
  '<!-- Edit the *.stories.ts guidance or the fenced ranges in CONTEXT.md, then re-run `pnpm generate:context`. -->',
]

function done(lines) {
  return `${lines.join('\n').replace(/\n{3,}/g, '\n\n').trim()}\n`
}

/**
 * The entry point, and the only file meant to be read whole: how to import, the invariants, and one row per component.
 *
 * The per-component detail lives in components/, one file each, because this file is the tax every reader pays. Inlining all 42 made it ~21k tokens to answer "which button prop sets the icon?" — a question a ~400-token file answers. Rows carry enough to choose; the file carries enough to use.
 */
export function renderIndex({ storybook, invariants, components }) {
  const out = [...BANNER]
  const push = (...lines) => out.push(...lines)

  push(
    '',
    '# Using @louislp/trusty-ui',
    '',
    'The context that normally lives in the `trusty-ui` repository — which component to',
    'reach for, which one *not* to, and the invariants a consuming app has to hold —',
    'packaged for the repositories that only have this library installed.',
    '',
    '**Start here, then open the one component you need** from the table at the end:',
    'each has its own file under `components/`, with its guidance, props, events,',
    'slots, and examples. Every one of them is generated from that component\'s own',
    'source, so it is current by construction; guidance that is not there is not',
    'guidance this library gives.',
    '',
    '## How to import',
    '',
    '```ts',
    'import { TrustyButton, TrustyFormItem } from \'@louislp/trusty-ui\'',
    '```',
    '',
    'One entry, always. There are no per-component or per-category subpaths — see',
    '"The single entry" below. Styles need one import in the app\'s own entry:',
    '',
    '```ts',
    'import \'@louislp/trusty-ui/src/styles/main.css\'',
    '```',
    '',
    '## Where the rest lives',
    '',
    '| | |',
    '| --- | --- |',
    '| One component in full | `components/TrustyThing.md`, linked from the table below |',
    '| Setup, the form system in code, authoring rules | `README.md`, beside this file |',
    '| How a screen should look and read — tokens, voice, spacing, actions | `ui-ux-principles.md`, beside this file |',
    '| Version history | `CHANGELOG.md`, beside this file |',
    `| Every prop, variant, and a live playground | ${storybook ? `[Storybook](${storybook})` : '`pnpm storybook` in the trusty-ui repository'} |`,
    '| All of it at once, structured, for tooling | `manifest.json`, beside this file |',
    '',
    '---',
    '',
    '## Invariants',
    '',
    'Verbatim from the library\'s own `CONTEXT.md`.',
    '',
  )

  for (const section of invariants)
    push(`### ${section.title}`, '', section.body, '')

  push(
    '---',
    '',
    '## Choosing a component',
    '',
    `${components.length} components. \`Depth\` is the composition vocabulary above; the grouping is`,
    'Storybook\'s. Open a component\'s file before using it — the summary here is one',
    'sentence, and the reasons *not* to reach for it are in there.',
    '',
    '| Component | Group | Depth | What it is |',
    '| --- | --- | --- | --- |',
  )
  for (const c of components)
    push(`| [${c.name}](${componentPath(c.name)}) | ${cell(c.category)} | ${c.depth} | ${cell(c.summary)} |`)

  return done(out)
}

/** One component, in full — the unit an agent actually reads to use one. */
export function renderComponent(c) {
  const out = [...BANNER]
  const push = (...lines) => out.push(...lines)

  push('', `# ${c.name}`, '', `\`${c.category}\` · composition depth: \`${c.depth}\``, '')
  if (c.description)
    push(c.description, '')

  push('```ts', `import { ${c.name} } from '@louislp/trusty-ui'`, '```', '')

  if (c.props.length) {
    push('## Props', '', '| Prop | Type | Default | Description |', '| --- | --- | --- | --- |')
    for (const p of c.props) {
      const type = `\`${cell(p.type)}\``
      const dflt = p.default ? `\`${cell(p.default)}\`` : (p.required ? '*required*' : '—')
      push(`| \`${p.name}\` | ${type} | ${dflt} | ${cell(p.description)} |`)
    }
    push('')
  }

  if (c.events.length) {
    push('## Events', '')
    for (const e of c.events)
      push(`- \`${e.name}\`${e.type ? ` — \`${cell(e.type)}\`` : ''}${e.description ? ` — ${cell(e.description)}` : ''}`)
    push('')
  }

  if (c.slots.length) {
    push('## Slots', '')
    for (const s of c.slots)
      push(`- \`${s.name}\`${s.description ? ` — ${cell(s.description)}` : ''}`)
    push('')
  }

  if (c.stories.length) {
    push('## Examples in Storybook', '')
    for (const s of c.stories)
      push(`- ${s.name}${s.description ? ` — ${cell(s.description)}` : ''}`)
    push('')
  }

  push('---', '')
  if (c.storybook)
    push(`[Open ${c.name} in Storybook](${c.storybook}) · [All components](../using-trusty-ui.md)`)
  else
    push('[All components](../using-trusty-ui.md)')

  return done(out)
}
