// Generates context/ — the copy of this library's context that travels with the published package, for consumers who have node_modules and nothing else.
//
//   node scripts/generate-context.mjs [--check]   (or: pnpm generate:context [--check])
//
// Almost everything here is derived, never authored:
//
//   CONTEXT.md, ranges fenced <!-- consumer:start --> … <!-- consumer:end -->  → the "Invariants" section
//   src/components/**/*.stories.ts  → category, guidance prose, story list
//   src/components/**/*.vue         → props, events, slots (via vue-component-meta, the extractor Storybook's autodocs uses)
//   docs/ui-ux-principles.md        → copied verbatim, banner prepended
//
// so the digest cannot say anything the repo does not already say. AGENTS.md makes the stories the *only* prop documentation precisely so it can't drift, and a hand-written API doc would put that straight back. The one authored input, ui-ux-principles.md, is exempt because it documents no API: it carries the screen-building conventions that no story, token file or type can state, and it names the code as the winner on any conflict.
//
// context/ is COMMITTED, not gitignored, for the same reason icons.generated.ts is: it must be reviewable in the diff that changes it, and CI's `context-generated` job runs it with `--check`, which fails the pipeline when the two disagree. Nothing that changes without a source edit reaches the output — no timestamp, no package version — since either would make every release commit fail that gate.
//
// This file is the wiring, and holds nothing else; `generated.mjs` writes or checks what it renders. `context/model.mjs` reads the repository into a ContextModel (which is what manifest.json serialises); `context/render.mjs` turns that model into markdown, and is pure, so it can be tested by calling it.
import { readFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { buildContextModel } from './context/model.mjs'
import { componentPath, renderComponent, renderIndex } from './context/render.mjs'
import { runGenerator } from './generated.mjs'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

// The hosted Storybook, from package.json's `homepage` — the GitHub Pages deployment CI publishes. Absent or empty, the digest simply carries no links rather than inventing one. If the repo or Pages site moves, fix `homepage` and re-run.
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
const storybookUrl = (pkg.homepage ?? '').replace(/\/$/, '')

const model = await buildContextModel({ root, storybookUrl })

// The one piece of consumer guidance that is authored rather than derived: how a screen BUILT WITH the library should look and read, which no story or token file states. It is authored in docs/ and copied here so context/ stays a directory nothing edits by hand, and so the `context-generated` gate covers it like everything else.
const principles = readFileSync(join(root, 'docs', 'ui-ux-principles.md'), 'utf8').trimEnd()

const files = {
  'context/using-trusty-ui.md': renderIndex(model),
  'context/manifest.json': `${JSON.stringify(model, null, 2)}\n`,
  'context/ui-ux-principles.md': `<!-- AUTO-GENERATED by scripts/generate-context.mjs — do not edit by hand. -->\n<!-- Edit docs/ui-ux-principles.md, then re-run \`pnpm generate:context\`. -->\n\n${principles}\n`,
}
for (const component of model.components)
  files[join('context', componentPath(component.name))] = renderComponent(component)

// context/ is owned outright, so a renamed or deleted component leaves as a deletion in the diff instead of a stale file the gate would never notice.
runGenerator({ name: 'generate:context', root, files, owns: ['context'] })
