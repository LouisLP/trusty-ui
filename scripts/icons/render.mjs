// The icons module: pure over source text and resolved icon data, so it is tested by calling it. generate-icons.mjs is the wiring — it reads src/ and @iconify-json/*.

// A quoted `collection:icon` literal: both halves kebab-case, the quote closing straight after. Backticks don't count, so a name in a doc comment's code span is not bundled.
const ICON_LITERAL = /(['"])([a-z0-9]+(?:-[a-z0-9]+)*:[a-z0-9]+(?:-[a-z0-9]+)*)\1/g

/** Every Iconify name quoted in `sources`, deduplicated and sorted. */
export function findIconNames(sources) {
  const names = new Set()
  for (const source of sources) {
    for (const [, , name] of source.matchAll(ICON_LITERAL))
      names.add(name)
  }
  return [...names].sort()
}

/** The source of src/icons/icons.generated.ts, from `{ 'collection:icon': IconifyIcon }`. */
export function renderIcons(icons) {
  const entries = Object.keys(icons)
    .sort()
    .map(name => `  '${name}': ${JSON.stringify(icons[name])},`)
    .join('\n')

  return `// AUTO-GENERATED by scripts/generate-icons.mjs — do not edit by hand.\n`
    + `// Iconify data for every \`collection:icon\` name the components quote (scanned\n`
    + `// from src/), inlined so they render offline with no API fetch.\n`
    + `import type { IconifyIcon } from '@iconify/vue'\n\n`
    + `export const bundledIcons: Record<string, IconifyIcon> = {\n${entries}\n}\n`
}
